      <h2 class="section-title">Preparing for the<br><em>Newborn Photoshoot</em></h2>
      <p class="section-sub">Book your newborn shoot before your due date, feed the baby just before the session and carry spare diapers and wipes. Preparation is crucial when it comes to newborn baby photoshoots. Firstly, it is advisable to select a newborn photographer in Pune months before your delivery is due. Share your ideas, and concerns about what kind of pictures you like, what poses and maybe some props you want to use. During the day of the shoot, it is advised that you wake up your baby 1-2 hours before the shoot so that he/she may sleep during the shoot.</p>
      <p class="section-sub section-sub-gap">The baby should be fed before the shoot so he or she is happy during the photoshoot. Do not dress your newborn too tightly or in tightly fitting clothes to leave marks on their skin. Carry spare diapers, wipes, and formula if you are using them for your child. But most importantly before new born baby photoshoot take your time and remain calm. Your baby will feel your energy and this will keep him calm and give you those beautiful, relaxed shots that make newborn photography so wonderful.</p>
