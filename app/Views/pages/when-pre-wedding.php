<!-- Best time of day -->
<section class="section section-white">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">Best Time of Day<br><em>for the Shoot</em></h2>
    </div>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">The best light comes during golden hour: roughly the first hour after sunrise and the last hour before sunset. The sun is low, so the light is warm and soft, faces look even and there are no hard shadows under the eyes.</p>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">A sunrise start also means fewer people at public places like gardens and forts, and cooler weather. An evening slot gives you warm sunset colours, and after sunset there is a short blue hour that works well with city lights or fairy lights.</p>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;">Around midday the light is harsh and flat. We usually use that time for travel, outfit changes, lunch or indoor and shaded spots.</p>
  </div>
