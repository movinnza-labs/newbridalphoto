<!-- How long before the wedding -->
<section class="section section-off">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">How Many Months Before the Wedding<br><em>Should You Shoot?</em></h2>
    </div>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">We suggest doing your pre wedding shoot about three to six months before the wedding. This window works well for most couples for a few simple reasons.</p>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">First, it leaves enough time for editing. Selecting photos, retouching them and cutting a film or song takes a few weeks. Second, you will want some of these photos for save-the-date cards, digital invites and social media posts, and those usually go out two to three months before the wedding. Third, many couples like to show the photos or film at the wedding itself, on a screen or a welcome board, and that needs the final files well before the day.</p>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">Shooting too early has its own problem. If you shoot a year ahead, your hair, look or even the season may be very different by the wedding. Shooting too late, in the last few weeks, adds stress at a time when you are already busy, and leaves no room for a second attempt if it rains.</p>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;">If your wedding date is close, a shoot four to six weeks before is still possible. Just tell us early so we can plan the editing around your dates.</p>
  </div>
</section>

<!-- Best months around Pune -->
<section class="section section-white">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">Best Season in Pune<br><em>Month by Month</em></h2>
      <p class="section-sub">Each season around Pune gives a different look. Pick the one that suits your style, then choose your spots from our list of <a href="<?= base_url('/pre-wedding-shoot-locations-in-pune/') ?>" style="color:var(--gold);">pre wedding shoot locations in Pune</a>.</p>
    </div>
    <h3 style="font-family:var(--font-serif);font-size:1.3rem;color:var(--text-primary);margin-bottom:.8rem;">Winter: October to February</h3>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1.5rem;">This is the most popular time. The air is clear, the light is soft for most of the day and the weather is cool, so heavy outfits and lehengas are comfortable. Forts, gardens and lakes all look good. Because it is peak season, popular spots and dates get booked quickly, so plan early.</p>
    <h3 style="font-family:var(--font-serif);font-size:1.3rem;color:var(--text-primary);margin-bottom:.8rem;">Monsoon: June to September</h3>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1.5rem;">The hills around Pune turn deep green, waterfalls start flowing and mist rolls over places like Sinhagad, Mulshi and Lonavala. The photos can look magical. The risk is rain, slippery paths and sudden changes in light, so keep a backup date, choose outfits that can handle a little water and avoid long, heavy trains.</p>
    <h3 style="font-family:var(--font-serif);font-size:1.3rem;color:var(--text-primary);margin-bottom:.8rem;">Summer: March to May</h3>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1.5rem;">Days are hot, the midday light is harsh and the landscape is dry and brown. You can still get lovely photos if you shoot at sunrise and in the last hour before sunset, carry water, and pick shaded gardens or indoor sets for the middle of the day.</p>
    <h3 style="font-family:var(--font-serif);font-size:1.3rem;color:var(--text-primary);margin-bottom:.8rem;">Month-by-Month at a Glance</h3>
    <ul class="pkg-detail-list">
      <li><strong>January and February:</strong> Cool mornings, clear skies and soft light all day. Among the best months for any style of shoot.</li>
      <li><strong>March to May:</strong> Hot and dry. Shoot only at sunrise and sunset, and use shaded or indoor spots in between.</li>
      <li><strong>June:</strong> The monsoon usually arrives around mid-June. Early rains bring dramatic clouds, but the hills are not fully green yet.</li>
      <li><strong>July and August:</strong> Peak monsoon. The greenest, mistiest landscapes and full waterfalls, with the highest chance of rain on your date.</li>
      <li><strong>September:</strong> Rain eases, the hills are still green and the light often clears in the evenings. A good balance of greenery and dry weather.</li>
      <li><strong>October:</strong> The monsoon withdraws. Early October can be warm and humid; from mid-October the weather settles and the peak season begins.</li>
      <li><strong>November and December:</strong> Cool, dry and clear. The most popular months, so book dates and locations early.</li>
    </ul>
