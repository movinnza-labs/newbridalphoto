<!-- Festivals and wedding season -->
<section class="section section-off">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">Timing Around Festivals<br><em>and Wedding Season</em></h2>
    </div>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">The calendar matters as much as the weather. A few things to keep in mind when you pick your date:</p>
    <ul class="pkg-detail-list">
      <li><strong>Peak wedding season:</strong> November to February has the most wedding dates, so photographers, makeup artists and popular venues book up fast. If your wedding falls in this window, shoot a few months earlier, for example in September or October.</li>
      <li><strong>Ganeshotsav and Diwali:</strong> During the Ganesh festival, central Pune is crowded and traffic is heavy, and around Diwali many people travel and vendors take time off. Plan city locations around these dates, or use them for festive-themed photos on purpose.</li>
      <li><strong>Weekends and holidays:</strong> Forts, gardens and hill stations like Lonavala get crowded on weekends and long weekends. A weekday shoot gives you emptier frames and more privacy.</li>
      <li><strong>Your own schedule:</strong> Avoid the last few weeks before the wedding, when shopping, rituals and guests take over. Leave enough time for editing and save-the-date cards.</li>
    </ul>
  </div>
</section>

<!-- How to plan -->
<section class="section section-white">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">How to Plan<br><em>Your Shoot Day</em></h2>
    </div>
    <ul class="pkg-detail-list">
      <li><strong>Outfits:</strong> Plan two or three outfits, from traditional to casual. Choose colours that stand out from the location, for example bright colours against green hills and soft pastels in gardens.</li>
      <li><strong>Permissions:</strong> Many forts, gardens, resorts and private sets need permission, and some charge a fee. Check this before the day so you are not stopped at the gate.</li>
      <li><strong>Backup date:</strong> Keep one spare date, especially in the monsoon, in case rain or poor light spoils the plan.</li>
      <li><strong>Travel time:</strong> Group nearby locations together so you do not lose the best light on the road.</li>
      <li><strong>Hair and makeup:</strong> For a sunrise shoot, makeup often starts before dawn. Fix the timing with your artist in advance.</li>
      <li><strong>Small comforts:</strong> Carry water, snacks, comfortable footwear for walking between spots, and a small kit with safety pins and tissues.</li>
      <li><strong>Invitation photos:</strong> If you want a photo for your wedding invitation or save-the-date, tell us in advance. The best ones tell your story and show real emotion, with a setting that suits you, such as hills in the background if you both love hiking.</li>
    </ul>
