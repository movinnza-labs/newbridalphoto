<!-- Monsoon shoots -->
<section class="section section-off">
  <div class="container">
    <div class="section-head">
      <div class="rule-center" style="margin-bottom:1.4rem;"></div>
      <h2 class="section-title">Monsoon <em>Pre-Wedding Shoots</em></h2>
    </div>
    <p style="font-size:.93rem;color:var(--text-muted);line-height:1.78;margin-bottom:1rem;">From July to September the ghats around Pune are at their most beautiful, and many couples choose the monsoon on purpose for the green hills, mist and waterfalls. It needs a little more planning than a winter shoot.</p>
    <ul class="pkg-detail-list">
      <li>Keep a backup date in case of very heavy rain, and decide the day before whether to go ahead.</li>
      <li>Choose light, quick-drying fabrics and avoid long trains that soak up mud. Carry a towel and a spare pair of footwear.</li>
      <li>Transparent umbrellas, raincoats in bright colours and covered spots like verandas or cafes make good backups and props.</li>
      <li>Stay away from cliff edges, fast-flowing water and slippery rocks, and follow any local closures at waterfalls and dams.</li>
    </ul>
  </div>
