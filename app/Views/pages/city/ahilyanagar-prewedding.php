        <p class="card-white-text"><strong>Best time:</strong> morning, roughly 7 to 10 am, before visitors arrive and the sun gets harsh.</p>
      </div>
      <div class="card-white card-white-padded-sm">
        <h3 class="card-white-title lvl-h4">Cavalry Tank Garden</h3>
