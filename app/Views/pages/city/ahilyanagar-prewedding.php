        <p class="card-white-text"><strong>Best time:</strong> the last hour before sunset for warm golden light, October to March.</p>
      </div>
      <div class="card-white card-white-padded-sm">
        <h3 class="card-white-title lvl-h4">Anand Dham Garden</h3>
