        <p class="card-white-text"><strong>Best time:</strong> July to October for waterfalls and greenery, and sunrise or sunset for soft light on the lake. Plan it as a full-day trip from the city.</p>
      </div>
      <div class="card-white card-white-padded-sm">
        <h3 class="card-white-title lvl-h4">Sina River Bank</h3>
