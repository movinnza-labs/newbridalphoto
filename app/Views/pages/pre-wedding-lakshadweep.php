<!-- Best Time to Go -->
<section class="section section-white">
  <div class="container">
    <div class="section-head">
      <div class="rule-center section-head-rule"></div>
      <h2 class="section-title lvl-h4">Best Time for a Pre Wedding Shoot<br><em>in Lakshadweep</em></h2>
    </div>
    <p class="article-text">The best time to plan your shoot is from about October to mid May. In these months the sea is calm, the sky is mostly clear and the lagoon water looks its brightest turquoise. This is also the best time for snorkelling and for any shots in or near the water.</p>
    <p class="article-text article-text-gap">Avoid the monsoon, which runs from about late May to September. The sea gets rough, heavy rain is common and boat and flight plans can change at short notice. Within a shoot day, we plan the beach frames for early morning and the last hour before sunset. The light is soft at these times and the white sand does not reflect harsh light onto faces.</p>
  </div>
</section>

<!-- How to Reach -->
<section class="section section-off">
  <div class="container">
    <div class="section-head">
      <div class="rule-center section-head-rule"></div>
      <h2 class="section-title lvl-h4">How to Reach Lakshadweep<br><em>and Plan Your Trip</em></h2>
    </div>
    <p class="article-text">Most couples fly to Kochi first and then take a flight from Kochi to Agatti, which has the only airport in Lakshadweep. From Agatti, boats take you to nearby islands such as Bangaram and Kavaratti. There are also passenger ships from Kochi, but they take much longer.</p>
    <p class="article-text article-text-gap">Entry to Lakshadweep is restricted, so every visitor needs an entry permit. The permit has to be arranged in advance, usually along with your stay booking, and only some islands are open to visitors. Please do not book flights until your permit and stay are confirmed.</p>
    <p class="article-text article-text-gap">We suggest keeping one spare day in your plan. Flights to Agatti are small and the weather can delay boats, so an extra day lets us reshoot if the sky is not right. Pack light, breathable outfits for the beach and one flowing gown or saree for the sunset frames.</p>
  </div>
</section>

